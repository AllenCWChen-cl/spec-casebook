// Write library/<feature>/README.md: a generated index of the feature's spec sets and platform tables.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PLATFORMS, draftsDir, featureDir, readManifest } from './library.ts';
import { listSpecSets } from './specs.ts';

const mb = (b: number) => `${(b / 1048576).toFixed(1)} MB`;

export function writeFeatureIndex(feature: string) {
  const sets = listSpecSets(feature);
  const lines: string[] = [];
  const title = PLATFORMS.map(p => readManifest(feature, p)?.title).find(Boolean) ?? feature;
  lines.push(`# ${title}`, '', `Feature ID \`${feature}\`. Generated by the casebook scripts; do not edit by hand.`, '');
  lines.push('## Approved test-case tables', '', '| Platform | Version | Approved | Cases | Spec set | Files |', '|---|---|---|---|---|---|');
  for (const p of PLATFORMS) {
    const m = readManifest(feature, p);
    const dd = draftsDir(feature, p);
    const open = existsSync(dd) ? readdirSync(dd).filter(d => !d.startsWith('.') && !(m?.history ?? []).some(h => h.draft === d)) : [];
    const set = m ? sets.find(s => s.spec_set_sha256 === m.spec_set_sha256)?.folder ?? '—' : '—';
    lines.push(m
      ? `| ${p === 'ios' ? 'iOS' : 'Android'} | v${m.version} | ${m.approved_at.slice(0, 10)} | ${m.cases} | \`specs/${set}\` | [cases.xlsx](${p}/cases.xlsx) · [cases.csv](${p}/cases.csv) · [cases.html](${p}/cases.html) · [requirements](${p}/requirements.md)${open.length ? ` · open drafts: ${open.join(', ')}` : ''} |`
      : `| ${p === 'ios' ? 'iOS' : 'Android'} | — | — | — | — | ${open.length ? `open drafts: ${open.join(', ')}` : 'not started'} |`);
  }
  lines.push('', '## Spec sets received', '', 'Original files are kept locally and are not committed; their SHA-256 is in each `spec-set.json`.', '');
  for (const s of [...sets].reverse()) {
    lines.push(`### specs/${s.folder}`, '', `Received ${s.received_at.slice(0, 10)} · set SHA-256 \`${s.spec_set_sha256.slice(0, 16)}…\``, '');
    for (const f of s.files) lines.push(`- ${f.name} (${mb(f.bytes)}, \`${f.sha256.slice(0, 12)}…\`)`);
    lines.push('');
  }
  lines.push('## Layout', '', '```',
    `${feature}/`,
    '  README.md              this index',
    '  specs/<date>/          one folder per spec set received (originals git-ignored, spec-set.json + extracted text kept)',
    '  ios/ | android/        one approved table per platform',
    '    cases.csv            approved table (source of truth)',
    '    cases.xlsx, cases.html  generated views',
    '    requirements.md      requirements behind the Spec Ref column',
    '    manifest.json        version, approval date, spec checksums, history',
    '    history/             earlier approved versions',
    '    drafts/<id>/         drafts, update plans, review decisions',
    '    runs/<date>/         evidence from running the table on a build',
    '    ebugs/<date>/        eBug drafts, review page and filing records',
    '```', '');
  writeFileSync(join(featureDir(feature), 'README.md'), lines.join('\n'));
}
